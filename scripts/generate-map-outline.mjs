/**
 * Bakes the locator map's geometry into src/lib/geo.ts.
 *
 * The day locator needs a real Peru outline, not a hand-drawn approximation.
 * This pulls it from Natural Earth (via the `world-atlas` package), projects it
 * once, and writes out a plain SVG path plus the matching projection constants
 * so runtime code can place a lat/lng dot on the same frame.
 *
 * Run it only when the frame changes:
 *   npm i --no-save world-atlas topojson-client
 *   node scripts/generate-map-outline.mjs
 *
 * Neither package is a project dependency — the output is committed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const world = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8'));
const countries = feature(world, world.objects.countries);

const PERU = 'Peru';
const peru = countries.features.find((f) => f.properties.name === PERU);
if (!peru) throw new Error('Peru not found in the country set');

/** The frame: Peru's bounding box with a little air around it. */
const bounds = (() => {
  let minLng = 180;
  let maxLng = -180;
  let minLat = 90;
  let maxLat = -90;
  const walk = (coords) => {
    if (typeof coords[0] === 'number') {
      const [lng, lat] = coords;
      minLng = Math.min(minLng, lng);
      maxLng = Math.max(maxLng, lng);
      minLat = Math.min(minLat, lat);
      maxLat = Math.max(maxLat, lat);
      return;
    }
    coords.forEach(walk);
  };
  walk(peru.geometry.coordinates);
  const padLng = (maxLng - minLng) * 0.06;
  const padLat = (maxLat - minLat) * 0.06;
  return { minLng: minLng - padLng, maxLng: maxLng + padLng, minLat: minLat - padLat, maxLat: maxLat + padLat };
})();

/**
 * Equirectangular, with longitudes squeezed by cos(mid-latitude) so the country
 * isn't stretched sideways. Peru spans ~18° of latitude, so a single standard
 * parallel is plenty for a 200px locator.
 */
const midLat = (bounds.minLat + bounds.maxLat) / 2;
const kx = Math.cos((midLat * Math.PI) / 180);

const WIDTH = 200;
const spanX = (bounds.maxLng - bounds.minLng) * kx;
const spanY = bounds.maxLat - bounds.minLat;
const scale = WIDTH / spanX;
const HEIGHT = Math.round(spanY * scale);

const projectRaw = (lng, lat) => [
  (lng - bounds.minLng) * kx * scale,
  (bounds.maxLat - lat) * scale, // SVG y grows downward
];

const round = (n) => Math.round(n * 10) / 10;

/** Drop points closer together than `min` px — a 200px map cannot show them. */
function toPath(geometry, min = 0.7) {
  const rings = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  const parts = [];
  for (const polygon of rings) {
    for (const ring of polygon) {
      let d = '';
      let last = null;
      for (const [lng, lat] of ring) {
        const [x, y] = projectRaw(lng, lat).map(round);
        if (last && Math.abs(x - last[0]) < min && Math.abs(y - last[1]) < min) continue;
        d += `${d ? 'L' : 'M'}${x} ${y}`;
        last = [x, y];
      }
      if (d) parts.push(`${d}Z`);
    }
  }
  return parts.join('');
}

/** Everything else that falls inside the frame, drawn faintly for context. */
const inFrame = (f) => {
  let hit = false;
  const walk = (coords) => {
    if (hit) return;
    if (typeof coords[0] === 'number') {
      const [lng, lat] = coords;
      if (lng > bounds.minLng && lng < bounds.maxLng && lat > bounds.minLat && lat < bounds.maxLat) hit = true;
      return;
    }
    coords.forEach(walk);
  };
  walk(f.geometry.coordinates);
  return hit;
};

const neighbours = countries.features
  .filter((f) => f.properties.name !== PERU && inFrame(f))
  .map((f) => toPath(f.geometry, 5.5))
  .join('');

const out = `/**
 * Locator-map geometry, generated by scripts/generate-map-outline.mjs from
 * Natural Earth data (public domain) via the world-atlas package.
 *
 * Do not hand-edit: re-run the script instead. \`project\` matches the same
 * frame the paths were drawn in, so a lat/lng lands exactly where it should.
 */

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

const MIN_LNG = ${bounds.minLng};
const MAX_LAT = ${bounds.maxLat};
const KX = ${kx};
const SCALE = ${scale};

/** Peru's coastline and borders. */
export const PERU_PATH =
  '${toPath(peru.geometry, 0.7)}';

/** Neighbouring countries inside the same frame, for context. */
export const NEIGHBOURS_PATH =
  '${neighbours}';

/** Project a coordinate into the same frame as the paths above. */
export function project(lat: number, lng: number): { x: number; y: number } {
  return {
    x: (lng - MIN_LNG) * KX * SCALE,
    y: (MAX_LAT - lat) * SCALE,
  };
}
`;

writeFileSync('src/lib/geo.ts', out);
console.log(`wrote src/lib/geo.ts — ${WIDTH}×${HEIGHT}, Peru path ${toPath(peru.geometry, 0.7).length} chars, neighbours ${neighbours.length} chars`);
